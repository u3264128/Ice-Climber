"""Execute NES hammer and Topi routines at permanent stone columns."""
import hashlib
import json

from plan_mountains import PlanningMachine
from test_game import BASE
from test_nes_objects import COMPARED, c64_read, nes_view
from test_original_physics import Reference
from transplant_objects import map_ram


def material_rules():
    machine = PlanningMachine()
    a, labels = machine.ram, machine.labels
    a[labels['state']], a[labels['mountain']] = 1, 31
    machine.call('setup_level')
    cases = 0
    for player in (0, 1):
        a[labels['player_index']] = player
        for layer in (0, 1):
            # Upper raw2 is not generated by the NES; lower raw2 is short ice.
            for value in ((0, 1, 3, 4, 255) if layer == 0 else (0, 1, 2, 3, 4, 255)):
                source = Reference()
                source.ram[2] = 2          # DAF2's original removal increment
                source.ram[3:5] = (0x400+layer*256).to_bytes(2, 'little')
                source.ram[0x400+layer*256] = value
                source.call(0xDAF2)
                broken = source.ram[0x400+layer*256] != value
                assert broken == (value in (1, 2))
                packed = 0 if value == 255 else 1 if value == 1 else 2 if value == 2 or (value == 4 and layer == 0) else 3
                for plane in (0, 1):
                    a[0x400+plane*256:0x4D8+plane*256] = bytes([packed if plane == layer else 0])*216
                a[labels['pxlo']:labels['pxhi']+1] = (96+52).to_bytes(2, 'little')
                a[labels['face']] = a[labels['cam']] = 0
                a[labels['rowidx']] = 1
                before = bytes(a[0x400:0x5D8])
                machine.call('normal_break_head')
                changed = sum(x != y for x, y in zip(before, a[0x400:0x5D8]))
                assert changed == int(broken), ('hammer material', player, layer, value, changed, broken)
                cases += 1
    return dict(cases=cases, players=2, stone_raw_values=[0, 3, 4],
                breakable_raw_values=[1, 2], source_entry='DAF2')


def topi_crossing(mountain, players, direction):
    machine = PlanningMachine()
    a, labels = machine.ram, machine.labels
    a[labels['state']], a[labels['mountain']] = 1, mountain
    a[labels['game_mode']] = players-1
    machine.call('setup_level')
    a[1] = 0x34
    for obj in range(11):
        for base in (0x91, 0x9C, 0xA7, 0xB2, 0xBD, 0x382, 0x3A6,
                     0x3B1, 0x3BC, 0x3C7, 0x3D2, 0x3DD, 0x3E8):
            machine.write(map_ram(base+obj), 0)
    post_x = 88 if mountain == 5 else 120
    start_x = post_x-20*direction
    for address, value in ((0x93, 255), (0x9E, start_x), (0xA9, 200),
                           (0xB4, 1), (0xBF, direction & 255), (0x3A8, 128),
                           (0x3BE, 16), (0x3DF, 0xA0), (0x3EA, 0x40)):
        machine.write(map_ram(address), value)
    source = nes_view(machine)
    assert post_x in source.ram[0x600:0x60B], ('missing real column', mountain)
    terrain = bytes(source.ram[0x400:0x5D8])
    columns = bytes(a[0xE000:0xE800])
    positions = []
    for tick in range(100):
        # The original frame runs the Topi controller, object motion, and
        # player-only column collision. The C64 runs their relocated code.
        for entry in (0xEFEC, 0xEE0D, 0xE0B9):
            source.call(entry)
            machine.call(f'N_{entry:04X}')
        for address in COMPARED:
            assert c64_read(machine, address) == source.ram[address], (
                'Topi column crossing', mountain, players, direction, tick, hex(address))
        assert bytes(source.ram[0x400:0x5D8]) == terrain
        assert bytes(a[0xE000:0xE800]) == columns
        positions.append(source.ram[0x9E])
    assert min(positions) < post_x and max(positions) > post_x+8
    assert source.ram[0x93] == 255 and source.ram[0xA9] == 200
    return dict(mountain=mountain, players=players, direction=direction,
                ticks=len(positions), post_x=post_x, start_x=start_x,
                final_x=positions[-1], column_unchanged=True)


def main():
    report = dict(status='passed', hammer=material_rules(),
                  topis=[topi_crossing(mountain, players, direction)
                         for mountain in (5, 31) for players in (1, 2)
                         for direction in (1, -1)],
                  source_entries=['DAF2', 'EFEC', 'EE0D', 'E0B9'],
                  prg_sha256=hashlib.sha256((BASE/'c64/build/iceclimber_game.prg').read_bytes()).hexdigest())
    (BASE/'docs/verification/stone_rules.json').write_text(json.dumps(report, indent=2)+'\n')
    print('PASS original permanent-column hammer rules and Topi crossings', report)


if __name__ == '__main__':
    main()
