def decode_tile(data16: bytes) -> list[list[int]]:
    """Decode one 16-byte NES 2bpp tile -> 8x8 matrix of pixel values 0-3."""
    rows = []
    for y in range(8):
        lo = data16[y]
        hi = data16[y + 8]
        row = []
        for x in range(8):
            bit = 7 - x
            row.append(((hi >> bit) & 1) << 1 | ((lo >> bit) & 1))
        rows.append(row)
    return rows


def encode_tile(pix: list[list[int]]) -> bytes:
    """Encode an 8x8 matrix of 0-3 values back into 16 NES 2bpp bytes."""
    out = bytearray(16)
    for y in range(8):
        lo = hi = 0
        for x in range(8):
            lo = (lo << 1) | (pix[y][x] & 1)
            hi = (hi << 1) | ((pix[y][x] >> 1) & 1)
        out[y] = lo
        out[y + 8] = hi
    return bytes(out)


def chr_tiles(chr_bank: bytes) -> list[list[list[int]]]:
    """Decode a whole pattern table (4 KiB) into 256 tiles."""
    return [decode_tile(chr_bank[i * 16:i * 16 + 16]) for i in range(len(chr_bank) // 16)]


def palette_rgb(indices: list[int]) -> list[tuple[int, int, int]]:
    """Map 4 NES palette indices (bg0,bg1,bg2,bg3) to preview RGB."""
    return [NES_PALETTE[i & 0x3F] for i in indices]
